                                <p class="mb-2">6.3. Суб'єкт відносин, пов'язаних з&nbsp;персональними даними, подає запит щодо доступу (далі — запит) до&nbsp;персональних даних володільцю персональних даних.</p>
                                <p class="mb-2">6.4. У&nbsp;запиті зазначаються:</p>
