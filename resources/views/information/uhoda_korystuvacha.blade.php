                                <p class="mb-2">6.1. Порядок доступу до&nbsp;персональних даних третіх осіб визначається умовами згоди суб'єкта персональних даних, наданої володільцю персональних даних на&nbsp;обробку цих даних, або відповідно до&nbsp;вимог закону.</p>
