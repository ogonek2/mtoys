                                <h3 class="font-heading text-lg font-bold text-[#0E3A45] mb-3">7. Захист персональних даних</h3>
                                <p class="mb-2">7.1. Володільця бази персональних даних обладнано системними і&nbsp;програмно-технічними засобами та&nbsp;засобами зв'язку, які запобігають втратам, крадіжкам, несанкціонованому знищенню, викривленню, підробленню, копіюванню інформації.</p>
                                <p class="mb-2">7.2. Відповідальна особа організовує роботу, пов'язану із&nbsp;захистом персональних даних при їх&nbsp;обробці відповідно до&nbsp;закону.</p>
                                <p class="mb-2">7.3. Відповідальна особа зобов'язана:</p>
                                <ul class="list-disc list-inside space-y-1.5 ml-2 mb-3">
                                    <li>знати законодавство України в&nbsp;сфері захисту персональних даних;</li>
                                    <li>розробити процедури доступу до&nbsp;персональних даних;</li>
                                    <li>забезпечити виконання вимог законодавства;</li>
                                    <li>розробити порядок внутрішнього контролю;</li>
                                    <li>повідомляти про факти порушень;</li>
                                    <li>забезпечити зберігання документів, що&nbsp;підтверджують надання суб'єктом згоди.</li>
                                </ul>
                                <p class="mb-2">7.4. Відповідальна особа має право: отримувати документи; робити копії; брати участь в&nbsp;обговоренні; вносити пропозиції; одержувати пояснення; підписувати та&nbsp;візувати документи в&nbsp;межах компетенції.</p>
                                <p class="mb-2">7.5. Працівники зобов'язані дотримуватись вимог законодавства щодо обробки і&nbsp;захисту персональних даних.</p>
                                <p class="mb-2">7.6. Працівники зобов'язані не&nbsp;допускати розголошення персональних даних. Таке зобов'язання чинне після припинення діяльності.</p>
                                <p class="mb-2">7.7. У&nbsp;разі порушення вимог Закону працівники несуть відповідальність згідно законодавства України.</p>
                                <p>7.8. Персональні дані не&nbsp;повинні зберігатися довше, ніж це&nbsp;необхідно для мети, для якої такі дані зберігаються.</p>
                            </section>

                            <section>
                                <h3 class="font-heading text-lg font-bold text-[#0E3A45] mb-3">8. Права суб'єкта персональних даних</h3>
                                <p class="mb-2">8.1. Суб'єкт персональних даних має право:</p>
                                <ul class="list-disc list-inside space-y-1.5 ml-2">
                                    <li>знати про місцезнаходження бази персональних даних;</li>
                                    <li>отримувати інформацію про умови надання доступу;</li>
                                    <li>на&nbsp;доступ до&nbsp;своїх персональних даних;</li>
                                    <li>отримувати відповідь про збереження даних протягом тридцяти днів;</li>
                                    <li>пред'являти вимогу щодо зміни або знищення даних;</li>
                                    <li>на&nbsp;захист своїх персональних даних від незаконної обробки;</li>
                                    <li>звертатися до&nbsp;органів державної влади;</li>
                                    <li>застосовувати засоби правового захисту.</li>
                                </ul>
                            </section>

                            <section>
                                <h3 class="font-heading text-lg font-bold text-[#0E3A45] mb-3">9. Порядок роботи з&nbsp;запитами суб'єкта персональних даних</h3>
                                <p class="mb-2">9.1. Суб'єкт має право на&nbsp;одержання будь-яких відомостей про себе без зазначення мети запиту.</p>
