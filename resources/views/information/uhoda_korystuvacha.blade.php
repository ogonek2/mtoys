                                </ul>
                                <p class="mb-2">9.4. Строк вивчення запиту — не&nbsp;більше десяти робочих днів.</p>
                                <p>9.5. Запит задовольняється протягом тридцяти календарних днів з&nbsp;дня надходження.</p>
