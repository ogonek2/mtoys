                                    <li>найменування, місцезнаходження юридичної особи, яка подає запит;</li>
                                    <li>прізвище, ім'я та&nbsp;по&nbsp;батькові, а&nbsp;також інші відомості, що&nbsp;дають змогу ідентифікувати фізичну особу;</li>
                                    <li>відомості про базу персональних даних, стосовно якої подається запит;</li>
                                    <li>перелік персональних даних, що&nbsp;запитуються;</li>
